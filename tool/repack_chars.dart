/// Sprite normalizer — the P1 sprite-contract tool.
///
/// Problem it fixes: source sheets mix frame geometries (idle 32×32 cells,
/// run 64×64 cells with ~2× transparent padding). Drawing both into the same
/// destination box made walking art ~half the idle height.
///
/// What it does, per character:
///   1. slices every animation sheet into frames (manifest-declared cells)
///   2. computes each frame's alpha bounding box (a > kAlphaCut)
///   3. takes the UNION rect across ALL frames of ALL anims of that character
///   4. re-exports every frame cropped to that union rect → new sheets whose
///      cells are identical across anims, feet anchored at the cell bottom
///   5. writes a generated manifest (`lib/game/chars_norm_manifest.g.dart`)
///      with cell sizes + per-character display height
///
/// Union (not per-frame) cropping is deliberate: the pixel differences
/// between frames are the animation — feet bob, cloaks sway. A shared rect
/// preserves that motion while making the SCALE identical.
///
/// Run:  dart run tool/repack_chars.dart
/// Output: assets/sprites/chars_norm/*.png + lib/game/chars_norm_manifest.g.dart
library;

import 'dart:io';
import 'package:image/image.dart';

const kAlphaCut = 24; // pixels below this alpha count as empty

/// charKey → animName → (source path, frame count, frameW, frameH)
const spec = <String, Map<String, List<int>>>{
  'sk_base': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
    'death': [12, 64, 64],
  },
  'sk_warrior': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
    'death': [6, 64, 48],
  },
  'sk_rogue': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
    'death': [6, 64, 64],
  },
  'sk_mage': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
    'death': [6, 64, 64],
  },
  'knight': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
  },
  'tavern_a': {
    'idle': [4, 64, 64],
    'walk': [6, 64, 64],
  },
  'tavern_b': {
    'idle': [4, 64, 64],
    'walk': [6, 64, 64],
  },
  'wizzard': {
    'idle': [4, 32, 32],
    'run': [6, 64, 64],
  },
};

const stepTimes = {'idle': 0.22, 'run': 0.12, 'walk': 0.12, 'death': 0.14};

/// Alpha bbox of a frame image. Returns [x, y, w, h] or null when empty.
List<int>? alphaBBox(Image img) {
  var x0 = img.width, y0 = img.height, x1 = -1, y1 = -1;
  for (var y = 0; y < img.height; y++) {
    for (var x = 0; x < img.width; x++) {
      if (img.getPixel(x, y).a > kAlphaCut) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  if (x1 < 0) return null;
  return [x0, y0, x1 - x0 + 1, y1 - y0 + 1];
}

void main() {
  const srcDir = 'assets/sprites/chars';
  const outDir = 'assets/sprites/chars_norm';
  Directory(outDir).createSync(recursive: true);

  final manifest = StringBuffer();
  manifest.writeln('/// GENERATED by tool/repack_chars.dart — do not edit.');
  manifest.writeln('/// Normalized char sheets: identical cell geometry across');
  manifest.writeln('/// anims, feet anchored at the cell bottom.');
  manifest.writeln('library;');
  manifest.writeln();
  manifest.writeln(
      'class NormSheet { final String path; final int frames; final int cellW;'
      ' final int cellH; final double stepTime; const NormSheet(this.path,'
      ' this.frames, this.cellW, this.cellH, {this.stepTime = 0.12}); }');
  manifest.writeln();
  manifest.writeln('class NormChar { final int cellW; final int cellH;'
      ' final Map<String, NormSheet> anims; const NormChar(this.cellW,'
      ' this.cellH, this.anims); }');
  manifest.writeln();
  manifest.writeln('/// Natural display height for all characters (world px).');
  manifest.writeln('const kCharDisplayH = 56.0;');
  manifest.writeln();
  manifest.writeln('const normChars = <String, NormChar>{');

  for (final entry in spec.entries) {
    final key = entry.key;
    // Pass 1 — union bbox across every anim of this character.
    var ux0 = 1 << 30, uy0 = 1 << 30, ux1 = -1, uy1 = -1;
    final sheets = <String, List<Image>>{};
    for (final ae in entry.value.entries) {
      final anim = ae.key, s = ae.value;
      final file = File('$srcDir/${key}_$anim.png');
      if (!file.existsSync()) continue;
      final img = decodePng(file.readAsBytesSync())!;
      final frames = <Image>[];
      for (var i = 0; i < s[0]; i++) {
        frames.add(copyCrop(img,
            x: i * s[1], y: 0, width: s[1], height: s[2]));
      }
      sheets[anim] = frames;
      for (final f in frames) {
        final b = alphaBBox(f);
        if (b == null) continue;
        if (b[0] < ux0) ux0 = b[0];
        if (b[1] < uy0) uy0 = b[1];
        if (b[0] + b[2] > ux1) ux1 = b[0] + b[2];
        if (b[1] + b[3] > uy1) uy1 = b[1] + b[3];
      }
    }
    if (sheets.isEmpty || ux1 < 0) {
      stderr.writeln('!! $key: no art found, skipped');
      continue;
    }
    // +1px padding inside the union so strokes/glows never clip.
    final cw = ux1 - ux0 + 2, ch = uy1 - uy0 + 2;
    final cx = ux0 - 1, cy = uy0 - 1;

    // Pass 2 — re-export each anim cropped to the union rect.
    manifest.writeln("  '$key': NormChar($cw, $ch, {");
    for (final ae in sheets.entries) {
      final anim = ae.key, frames = ae.value;
      final out = Image(
          width: cw * frames.length, height: ch, numChannels: 4);
      for (var i = 0; i < frames.length; i++) {
        final cropped = copyCrop(frames[i],
            x: cx, y: cy, width: cw, height: ch);
        compositeImage(out, cropped, dstX: i * cw);
      }
      final name = '${key}_$anim.png';
      File('$outDir/$name').writeAsBytesSync(encodePng(out));
      final step = stepTimes[anim] ?? 0.12;
      manifest.writeln("    '$anim': NormSheet('chars_norm/$name',"
          ' ${frames.length}, $cw, $ch, stepTime: $step),');
    }
    manifest.writeln('  }),');
    stdout.writeln('$key: cell ${cw}x$ch'
        ' (${sheets.keys.join(", ")})');
  }
  manifest.writeln('};');
  File('lib/game/chars_norm_manifest.g.dart')
      .writeAsStringSync(manifest.toString());
  stdout.writeln('wrote lib/game/chars_norm_manifest.g.dart');
}
